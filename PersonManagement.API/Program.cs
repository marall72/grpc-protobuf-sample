using FluentValidation;
using Microsoft.EntityFrameworkCore;
using PersonManagement.API.Services;
using PersonManagement.Application.Abstractions;
using PersonManagement.Application.Services;
using PersonManagement.Application.Validation;
using PersonManagement.Infrastructure.Persistence;
using PersonManagement.Infrastructure.Repositories;
using Serilog;
var builder = WebApplication.CreateBuilder(args);
builder.Host.UseSerilog((ctx, cfg) => cfg.ReadFrom.Configuration(ctx.Configuration).Enrich.FromLogContext().WriteTo.Console());
builder.Services.AddGrpc();
builder.Services.AddDbContext<PersonDbContext>(o => o.UseSqlServer(builder.Configuration.GetConnectionString("PersonDatabase")));
builder.Services.AddScoped<IPersonRepository, PersonRepository>();
builder.Services.AddScoped<IPersonService, PersonService>();
builder.Services.AddValidatorsFromAssemblyContaining<PersonDataValidator>();
var app = builder.Build();
app.MapGrpcService<PersonsGrpcService>();
app.MapGet("/", () => "Person Management gRPC API. Use a gRPC client to call the service.");
app.Run();
